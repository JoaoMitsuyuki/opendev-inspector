import { readFile } from 'node:fs/promises';
import path from 'node:path';
import type { Finding, Scanner } from '../core/types.js';
import { relativePath } from '../utils/text.js';

const LOCKFILES = [
  'package-lock.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'bun.lock',
  'bun.lockb',
];

export const dependencyScanner: Scanner = {
  name: 'dependencies',
  async scan(context) {
    const findings: Finding[] = [];
    const packageFiles = context.files.filter(
      (file) => path.basename(file) === 'package.json',
    );

    for (const file of packageFiles) {
      const relative = relativePath(context.root, file);
      let manifest: PackageManifest;
      try {
        manifest = JSON.parse(await readFile(file, 'utf8')) as PackageManifest;
      } catch {
        findings.push({
          ruleId: 'dependencies/invalid-package-json',
          module: 'dependencies',
          severity: 'high',
          title: 'Invalid package.json',
          description: 'The dependency manifest could not be parsed as JSON.',
          recommendation: 'Fix the JSON syntax before installing dependencies.',
          location: { path: relative },
        });
        continue;
      }

      const directory = path.dirname(file);
      const hasLockfile = context.files.some(
        (candidate) =>
          path.dirname(candidate) === directory &&
          LOCKFILES.includes(path.basename(candidate)),
      );
      if (!hasLockfile && hasDependencies(manifest)) {
        findings.push({
          ruleId: 'dependencies/missing-lockfile',
          module: 'dependencies',
          severity: 'medium',
          title: 'Dependency lockfile is missing',
          description:
            'Installs may resolve to different package versions over time.',
          recommendation:
            'Commit the lockfile generated by the package manager used by this project.',
          location: { path: relative },
        });
      }

      for (const [name, version] of dependencyEntries(manifest)) {
        if (version === '*' || version.toLowerCase() === 'latest') {
          findings.push({
            ruleId: 'dependencies/unbounded-version',
            module: 'dependencies',
            severity: 'medium',
            title: 'Unbounded dependency version',
            description: `${name} uses the version range ${version}, which is not reproducible.`,
            recommendation:
              'Use a bounded semantic version range and commit a lockfile.',
            location: { path: relative },
            evidence: `${name}@${version}`,
          });
        }
      }
    }

    return findings;
  },
};

interface PackageManifest {
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
}

function dependencyEntries(manifest: PackageManifest): [string, string][] {
  return Object.entries({
    ...manifest.dependencies,
    ...manifest.devDependencies,
    ...manifest.optionalDependencies,
    ...manifest.peerDependencies,
  });
}

function hasDependencies(manifest: PackageManifest): boolean {
  return dependencyEntries(manifest).length > 0;
}
